export function getFloor(number) {
  const floor = FLOORS.find(entry => entry.number === number);
  if (!floor) throw new RangeError(`Unknown floor: ${number}`);
  return floor;
}

export function getRoom(id) {
  const room = FLOORS.flatMap(floor => floor.rooms).find(entry => entry.id === id);
  if (!room) throw new RangeError(`Unknown room: ${id}`);
  return room;
}

export function searchCurriculum(query) {
  const terms = query.trim().toLocaleLowerCase().split(/\s+/).filter(Boolean);
  if (!terms.length) return [];
  return FLOORS.flatMap(floor => floor.rooms.flatMap(room => {
    const heading = `${floor.number} ${floor.title} ${floor.english} ${floor.summary} ${room.name} ${room.question}`.toLocaleLowerCase();
    const text = `${heading} ${room.challenge} ${room.topics.map(topic => `${topic.name} ${topic.summary}`).join(' ')}`.toLocaleLowerCase();
    if (!terms.every(term => text.includes(term))) return [];
    const topicIndex = room.topics.findIndex(topic => {
      const topicText = `${topic.name} ${topic.summary}`.toLocaleLowerCase();
      return terms.some(term => topicText.includes(term)) && terms.every(term => `${heading} ${topicText}`.includes(term));
    });
    return [{ floor: floor.number, roomId: room.id, roomName: room.name, floorTitle: floor.title, topicIndex,
      topicName: topicIndex >= 0 ? room.topics[topicIndex].name : null }];
  }));
}
