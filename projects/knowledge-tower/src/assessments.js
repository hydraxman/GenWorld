const ROOM_IDS = FLOORS.map(floor => floor.rooms.map(room => room.id));

function validateFloor(floor) {
  if (!Number.isInteger(floor) || floor < 1 || floor > ROOM_IDS.length) {
    throw new RangeError('floor must be an integer from 1 to 16');
  }
}

function validateAnswers(answers) {
  if (!Array.isArray(answers) || Object.getPrototypeOf(answers) !== Array.prototype
    || answers.length !== 4
    || Reflect.ownKeys(answers).length !== 5) {
    throw new TypeError('answers must be a dense array of exactly four integer indexes (0..3)');
  }
  for (let index = 0; index < 4; index += 1) {
    const descriptor = Object.getOwnPropertyDescriptor(answers, String(index));
    if (!descriptor || !('value' in descriptor) || !Number.isInteger(descriptor.value)
      || descriptor.value < 0 || descriptor.value > 3) {
      throw new RangeError(`answers[${index}] must be an integer from 0 to 3`);
    }
  }
}

export function getFloorAssessment(floor) {
  validateFloor(floor);
  return BANK[floor - 1].map(([prompt, options, correctIndex, explanation], index) => ({
    id: `assessment-v1-${ROOM_IDS[floor - 1][index]}`,
    roomId: ROOM_IDS[floor - 1][index],
    prompt,
    options: [...options],
    correctIndex,
    explanation,
  }));
}

export function gradeAssessment(floor, answers) {
  validateFloor(floor);
  validateAnswers(answers);
  const results = getFloorAssessment(floor).map((question, index) => ({
    roomId: question.roomId,
    correct: answers[index] === question.correctIndex,
    selectedIndex: answers[index],
    correctIndex: question.correctIndex,
    explanation: question.explanation,
  }));
  const score = results.filter(result => result.correct).length * 25;
  return { floor, score, passed: score >= 75, results };
}
